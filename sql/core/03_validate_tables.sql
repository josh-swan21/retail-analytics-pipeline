UNION ALL

SELECT
    'INVENTORY_ITEMS',
    COUNT_IF(inventory_item_id IS NULL),
    COUNT(inventory_item_id) - COUNT(DISTINCT inventory_item_id)
FROM INVENTORY_ITEMS

UNION ALL

SELECT
    'ORDER_LINES',
    COUNT_IF(order_line_id IS NULL),
    COUNT(order_line_id) - COUNT(DISTINCT order_line_id)
